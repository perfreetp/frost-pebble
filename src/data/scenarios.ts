/** 参考计划：由贪心排程器生成，保证满足全部硬规则。id 稳定，便于回放。 */
export function referenceAssignments(scenario: Scenario): Assignment[] {
  if (scenario.referencePlan && scenario.referencePlan.length > 0) {
    return scenario.referencePlan.map((seed, i) => ({
      id: `ref-${i + 1}`,
      shipId: seed.shipId,
      berthId: seed.berthId,
      pilotId: seed.pilotId,
      tugIds: [...seed.tugIds],
      startMin: seed.startMin,
    }));
  }
  return (planScenario(scenario) ?? []).map((a, i) => ({ ...a, id: `ref-${i + 1}` }));
}
