/** 一条典型半日潮曲线（米，理论最低潮面以上），覆盖 0–8 小时 */
const TIDE_CURVE: TidePoint[] = [
  { min: 0, heightM: 2.2 },
  { min: 45, heightM: 3.1 },
  { min: 90, heightM: 4.0 },
  { min: 135, heightM: 4.7 },
  { min: 180, heightM: 4.2 },
  { min: 225, heightM: 3.4 },
  { min: 270, heightM: 2.6 },
  { min: 315, heightM: 2.9 },
  { min: 360, heightM: 3.8 },
  { min: 405, heightM: 4.5 },
  { min: 450, heightM: 4.1 },
  { min: 495, heightM: 3.3 },
  { min: 540, heightM: 2.5 },
];

const tideAt = (min: number): number => {
  for (let i = 1; i < TIDE_CURVE.length; i += 1) {
    const a = TIDE_CURVE[i - 1];
    const b = TIDE_CURVE[i];
    if (min <= b.min) {
      const t = (min - a.min) / (b.min - a.min || 1);
      return Math.round((a.heightM + (b.heightM - a.heightM) * t) * 100) / 100;
    }
  }
  return TIDE_CURVE[TIDE_CURVE.length - 1].heightM;
};

/** 根据显式潮窗生成与之一致的潮高曲线（教师出题时用） */
export function buildTideFromWindows(
  windows: Array<{ from: number; to: number }>,
  horizonMin: number,
): TidePoint[] {
  const points: TidePoint[] = [];
  for (let t = 0; t <= horizonMin; t += 30) {
    const inWindow = windows.some((w) => t >= w.from && t <= w.to);
    points.push({ min: t, heightM: inWindow ? 4.6 : 2.4 });
  }
  return points;
}

