import { writeFileSync } from 'node:fs';
import { buildStrokeNodes, renderStroke, DEFAULT_PARAMS } from '../src/lib/generator';
import { getSkeleton } from '../src/lib/skeletons';
import { unionRings, ringsToPath, signedArea } from '../src/lib/geometry';
const p = { ...DEFAULT_PARAMS, weight: 130, contrast: 0.5, corner: 10, terminal: 'round' as const };
const sk = getSkeleton('永')!;
const st = buildStrokeNodes(sk.strokes[1], p.seed, '永', p.slant);
const r = renderStroke(st, p);
const selfU = unionRings([r]);
console.log('raw ring area', signedArea(r).toFixed(0), 'self-union polys', selfU.length, selfU.map(x=>x.map(y=>Math.abs(signedArea(y)).toFixed(0))));
console.log('nodes', st.nodes.map(n=>`${n.x.toFixed(0)},${n.y.toFixed(0)}`).join(' '));
writeFileSync('tests/out/heng.svg', `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="300"><g transform="translate(20,20) scale(0.5,-0.5) translate(0,-1000)"><path d="${ringsToPath([[r]])}" fill="#c0392b" fill-opacity="0.6"/><path d="${ringsToPath(selfU)}" fill="none" stroke="#1a6" stroke-width="3"/></g></svg>`);
