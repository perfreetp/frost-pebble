import { generateGlyph, DEFAULT_PARAMS, buildStrokeNodes, renderStroke } from '../src/lib/generator';
import { getSkeleton } from '../src/lib/skeletons';
import { unionRings, signedArea } from '../src/lib/geometry';
const ch='永';
const p = { ...DEFAULT_PARAMS, weight: 130, contrast: 0.5, corner: 10, terminal: 'round' as const };
const sk = getSkeleton(ch)!;
const strokes = sk.strokes.map(s => buildStrokeNodes(s, p.seed, ch, p.slant));
const rings = strokes.map(s => renderStroke(s, p));
rings.forEach((r,i)=>{ const u = unionRings([r]); console.log('stroke', i, strokes[i].id, 'ringpts', r.length, 'union polys', u.length, u.map(pp=>pp.length)); });
const all = unionRings(rings);
console.log('ALL polys', all.length, all.map(pp=>pp.map(rr=>Math.abs(signedArea(rr)).toFixed(0))));
